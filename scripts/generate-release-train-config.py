#!/usr/bin/env python3
"""Generate ReleaseTrainCatalogue.swift from Config/ReleaseTrains.json (focus-h8jf).

The JSON is canonical: the release scripts read it directly, and the app reads this generated
Swift. Run it after editing the JSON; the gate's `boundaries` stage checks that the committed
Swift is what this script would write, so the two cannot drift.

    python3 scripts/generate-release-train-config.py          # write
    python3 scripts/generate-release-train-config.py --check  # compare, exit 1 on drift
"""

import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE = ROOT / "Config" / "ReleaseTrains.json"
TARGET = ROOT / "Packages" / "FocusCore" / "Sources" / "FocusCore" / "Shell" / "ReleaseTrainCatalogue.swift"

REQUIRED_KEYS = [
    "bundleIdentifier",
    "displayName",
    "applicationSupportDirectory",
    "urlScheme",
    "feedURL",
    "productName",
    "latestReleaseTag",
]


def render(trains: dict) -> str:
    lines = [
        "// Generated by scripts/generate-release-train-config.py from Config/ReleaseTrains.json.",
        "// Do not edit: edit the JSON and re-run the script. `ReleaseTrain` reads this table and",
        "// `ReleaseTrainTests` holds every row to `ReleaseTrain.requiredKeys`.",
        "",
        "enum ReleaseTrainCatalogue {",
        "    static let values: [String: [String: String]] = [",
    ]
    for train in ("stable", "alpha"):
        row = trains[train]
        missing = [key for key in REQUIRED_KEYS if not row.get(key)]
        if missing:
            raise SystemExit(f"{SOURCE}: {train} is missing {', '.join(missing)}")
        lines.append(f'        "{train}": [')
        for key in REQUIRED_KEYS:
            value = row[key].replace("\\", "\\\\").replace('"', '\\"')
            lines.append(f'            "{key}": "{value}",')
        lines.append("        ],")
    lines += ["    ]", "}", ""]
    return "\n".join(lines)


def main() -> int:
    trains = json.loads(SOURCE.read_text())
    unexpected = sorted(set(trains) - {"stable", "alpha"})
    if unexpected:
        raise SystemExit(f"{SOURCE}: unknown train(s) {', '.join(unexpected)}")
    rendered = render(trains)
    if "--check" in sys.argv:
        current = TARGET.read_text() if TARGET.exists() else ""
        if current != rendered:
            print(f"FAIL {TARGET.relative_to(ROOT)} is not what {SOURCE.relative_to(ROOT)} renders; re-run this script")
            return 1
        print(f"ok   {TARGET.relative_to(ROOT)} matches {SOURCE.relative_to(ROOT)}")
        return 0
    TARGET.write_text(rendered)
    print(f"wrote {TARGET.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
