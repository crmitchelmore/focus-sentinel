#!/usr/bin/env python3
"""Hold the committed app icon to the palette and to the mark it is supposed to be.

    scripts/check-appicon.py

## Why the icon needs a check at all

`scripts/make-appicon.sh` is the source and `App/Assets.xcassets/AppIcon.appiconset/*.png` is
its output, committed because the build needs it as an input. Nothing in the gate has ever read
the output. A committed PNG that stopped matching its generator — hand-edited, half-regenerated,
or generated by a script somebody changed the colours in — would ship as the app's front door
with no stage noticing, and the icon is the one surface a person sees before they have installed
anything.

## What it reads, and why these three claims

Sampled from the pixels rather than re-run, because re-running the generator needs `swiftc` and
a minute, and the question is about the **bytes that ship**.

1. **The ground is Bench and the centre is Spruce.** The e11 direction gives the icon the app's
   own palette (§5.2 item 7); before e11b it was `systemTeal` over `systemBlue`, which is the
   platform's gradient rather than the app's mark. Two samples say which of those shipped.
2. **The inner ring is drawn at 128 px and dropped at 32.** The canvas says so at its own 32 px
   cell, and the reason is measured: at 32 the inner stroke is 1.6 px against a 3 px gap and the
   two rings merge into a smudge. Read as *how many times the ink changes* along the horizontal
   centre line — ten edges for two rings and a centre, six for one ring and a centre.
3. **Every declared size exists.** A `Contents.json` naming a file nobody wrote is an icon set
   that fails to build on a machine that has not run the generator.
"""

import struct
import subprocess
import sys
import tempfile
from pathlib import Path

REPOSITORY = Path(__file__).resolve().parent.parent
ICONS = REPOSITORY / "App/Assets.xcassets/AppIcon.appiconset"

#: The light values of the palette roles the icon is drawn in. `DesignTokens.Palette.Role`.
BENCH = (0xF2, 0xF4, 0xF3)
SPRUCE = (0x17, 0x6B, 0x73)

#: How far a sampled pixel may sit from the declared value, per channel. Non-zero because the
#: renderer antialiases and writes through a colour space; small, because a *different colour*
#: is not within three counts of the right one.
TOLERANCE = 3


def pixels(path: Path):
    """(width, height, rows) as 8-bit RGB, top-down, via `sips` — no image dependency."""
    with tempfile.TemporaryDirectory() as directory:
        bmp = Path(directory) / "icon.bmp"
        subprocess.run(
            ["sips", "-s", "format", "bmp", str(path), "--out", str(bmp)],
            check=True,
            capture_output=True,
        )
        data = bmp.read_bytes()
        offset = struct.unpack_from("<I", data, 10)[0]
        width, height = struct.unpack_from("<ii", data, 18)
        depth = struct.unpack_from("<H", data, 28)[0]
        stride = depth // 8
        row_bytes = ((width * stride + 3) // 4) * 4
        body = data[offset:]
        bottom_up = height > 0
        height = abs(height)
        rows = []
        for row in range(height):
            source = (height - 1 - row) if bottom_up else row
            base = source * row_bytes
            rows.append(
                [
                    (body[base + c * stride + 2], body[base + c * stride + 1], body[base + c * stride])
                    for c in range(width)
                ]
            )
        return width, height, rows


def near(sample, expected):
    return all(abs(a - b) <= TOLERANCE for a, b in zip(sample, expected))


def crossings(row, background):
    """How many times the ink turns on or off along a row.

    Cropped to the central 70 % of the width first. At the vertical middle the rounded square
    spans the full canvas less its own inset, so the outside of it is the *transparent* margin —
    which is not the background and would otherwise be counted as two more edges of ink. The
    crop is comfortably inside the outer ring at every size the icon is drawn at (the ring's own
    diameter is 62 % of the art).
    """
    margin = int(len(row) * 0.15)
    row = row[margin:len(row) - margin]
    count = 0
    previous = None
    for pixel in row:
        inked = not near(pixel, background)
        if previous is not None and inked != previous:
            count += 1
        previous = inked
    return count


def main() -> int:
    failed = 0

    def check(ok, message, detail=""):
        nonlocal failed
        if ok:
            print(f"ok   {message}")
        else:
            print(f"FAIL [appicon] {message}{(' — ' + str(detail)) if detail else ''}")
            failed = 1

    for name in sorted(p.name for p in ICONS.glob("*.png")):
        check((ICONS / name).stat().st_size > 0, f"{name} exists and is not empty")

    for name, expects_inner_ring in (("icon_512x512.png", True), ("icon_128x128.png", True), ("icon_32x32.png", False)):
        path = ICONS / name
        if not path.is_file():
            check(False, f"{name} is missing")
            continue
        width, height, rows = pixels(path)
        middle = rows[height // 2]

        check(near(middle[width // 2], SPRUCE), f"{name}: the centre is Spruce", middle[width // 2])
        # A little inside the rounded corner's arc, so the sample is on the ground rather than
        # on the transparent margin outside it.
        ground = rows[height // 5][width // 5]
        check(near(ground, BENCH), f"{name}: the ground is Bench", ground)

        edges = crossings(middle, ground)
        # Two edges per stroke crossed: outer ring, inner ring, centre, inner ring, outer ring.
        expected = 10 if expects_inner_ring else 6
        check(
            edges == expected,
            f"{name}: {'two rings' if expects_inner_ring else 'one ring'} and a centre on the "
            f"middle line",
            f"{edges} ink edges, expected {expected}",
        )

    print()
    if failed:
        print("APPICON CHECK FAILED", file=sys.stderr)
        return 1
    print("APPICON OK")
    return 0


if __name__ == "__main__":
    sys.exit(main())
